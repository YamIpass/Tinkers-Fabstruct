"""Generate the Fabric block render layer registration for Tinkers' Construct.

Forge reads the `render_type` field of a block model to pick the chunk render layer; Fabric has no such field, so
every non solid block has to be registered with `BlockRenderLayerMap`. The mapping is derived from the same data
Forge uses: the model a blockstate points at, following `parent` until a `render_type` shows up.

The generated class is a plain list of block ids, so it stays readable and diffable next to the upstream data.

Usage: gen_render_layers.py [--check]
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "src" / "main" / "resources" / "assets" / "tconstruct"
BLOCKSTATES = ASSETS / "blockstates"
MODELS = ASSETS / "models"
TARGET = ROOT / "src" / "main" / "java" / "slimeknights" / "tconstruct" / "shared" / "client" / "TinkerRenderLayers.java"

LAYERS = {
    "minecraft:translucent": "TRANSLUCENT",
    "minecraft:cutout_mipped": "CUTOUT_MIPPED",
    "minecraft:cutout": "CUTOUT",
}


def model_ids(node):
    """Collects every model id referenced by a blockstate json"""
    found = set()
    if isinstance(node, dict):
        for key, value in node.items():
            if key in ("model", "models") and isinstance(value, str):
                found.add(value)
            else:
                found |= model_ids(value)
    elif isinstance(node, list):
        for value in node:
            found |= model_ids(value)
    return found


def render_type(model_id, depth=0):
    """Resolves the render type of a model, following parents"""
    if depth > 4:
        return None
    path = MODELS / (model_id.split(":")[-1] + ".json")
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    if "render_type" in data:
        return data["render_type"]
    parent = data.get("parent")
    return render_type(parent, depth + 1) if parent else None


def collect():
    layers = {name: set() for name in LAYERS.values()}
    for path in sorted(BLOCKSTATES.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        block = "tconstruct:" + path.stem
        for model in model_ids(data):
            kind = render_type(model)
            name = LAYERS.get(kind)
            if name:
                layers[name].add(block)
    return layers


def write(layers):
    def entries(name):
        return "\n".join('    "%s",' % block for block in sorted(layers[name]))

    text = '''package slimeknights.tconstruct.shared.client;

import net.fabricmc.fabric.api.blockrenderlayer.v1.BlockRenderLayerMap;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;

/**
 * Block render layers for Tinkers' Construct, generated by {@code tools/gen_render_layers.py} from the
 * {@code render_type} entries of the block models (Forge reads them directly, Fabric needs this registration).
 */
public final class TinkerRenderLayers {
  private TinkerRenderLayers() {}

  private static final String[] TRANSLUCENT = {
%s
  };

  private static final String[] CUTOUT_MIPPED = {
%s
  };

  private static final String[] CUTOUT = {
%s
  };

  public static void register() {
    apply(TRANSLUCENT, RenderType.translucent());
    apply(CUTOUT_MIPPED, RenderType.cutoutMipped());
    apply(CUTOUT, RenderType.cutout());
  }

  private static void apply(String[] ids, RenderType layer) {
    for (String id : ids) {
      Block block = BuiltInRegistries.BLOCK.get(new ResourceLocation(id));
      if (block != Blocks.AIR) {
        BlockRenderLayerMap.INSTANCE.putBlock(block, layer);
      }
    }
  }
}
''' % (entries("TRANSLUCENT"), entries("CUTOUT_MIPPED"), entries("CUTOUT"))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")


def main():
    layers = collect()
    for name, blocks in layers.items():
        print(f"{name.lower()}: {len(blocks)}")
    if "--check" in sys.argv:
        print("check only, nothing written")
        return
    write(layers)
    print("wrote", TARGET.relative_to(ROOT))


if __name__ == "__main__":
    main()
