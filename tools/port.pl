for my $ln (@lines) {
  my $isComment = ($ln =~ m{^\s*(?:\*|//|/\*)}) ? 1 : 0;
  for my $r (@rules) {
    my ($kind, $from, $to) = @$r;
    if ($kind eq 'code' && $isComment) { next; }
    if ($kind eq 'fq') {
      $ln =~ s/\Q$from\E/$to/g;
    } else {
      $ln =~ s/$from/$to/g;
    }
  }
  $res .= $ln unless $ln =~ /^import [\w.]*\bFluidAction;/;
}
